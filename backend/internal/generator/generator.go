// Package generator renders the structured model into a Caddyfile. Output is
// deterministic (stable ordering) so that diffs and golden tests are exact.
package generator

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	cf "github.com/Krifmaz/CaddyHub/internal/caddyfile"
	"github.com/Krifmaz/CaddyHub/internal/model"
	"github.com/Krifmaz/CaddyHub/internal/registry"
)

// CredRef is a DNS credential with every field already resolved to what
// should appear in the Caddyfile: a placeholder such as {file./run/...} or
// {env.NAME} for secrets, or a literal for non-secret options.
type CredRef struct {
	Provider string
	Fields   map[string]string
}

// Env holds deployment wiring that comes from the environment, never from code.
type Env struct {
	AdminListen   string   // e.g. caddy-admin:2019 or unix//run/caddy-admin/admin.sock
	AdminOrigins  []string // allowed Host/Origin values for the admin API
	LogDir        string   // where Caddy writes logs, e.g. /var/log/caddy
	PanelUpstream string   // e.g. panel:8080, used when Settings.PanelDomain is set
	// TrustedProxyRanges maps preset id -> CIDRs (fetched/refreshed by the panel).
	TrustedProxyRanges map[string][]string
	// EABMacRef is the placeholder for the ACME EAB MAC key, if configured.
	EABMacRef string
	// CrowdSecKeyRef is the placeholder for the CrowdSec bouncer key.
	CrowdSecKeyRef string
	// ValidationMode omits the global logger. Used for the `caddy validate`
	// copy: a global log block redirects Caddy's own error output into the
	// log file, which would hide validation errors from the panel.
	ValidationMode bool
}

// Input is everything the generator needs.
type Input struct {
	Settings    model.Settings
	Sites       []model.Site
	Domains     []model.Domain
	Credentials map[int64]CredRef
	Snippets    []model.Snippet
	RawBlocks   []model.RawBlock
	Caps        registry.Capabilities
	Env         Env
}

// Output is the generated Caddyfile plus non-fatal warnings.
type Output struct {
	Caddyfile string   `json:"caddyfile"`
	Warnings  []string `json:"warnings"`
}

// CA presets map to ACME directory URLs. "letsencrypt" is Caddy's default
// issuer set (Let's Encrypt with ZeroSSL fallback), so no acme_ca is emitted.
var CAPresets = map[string]string{
	"letsencrypt":         "",
	"letsencrypt_staging": "https://acme-staging-v02.api.letsencrypt.org/directory",
	"zerossl":             "https://acme.zerossl.com/v2/DV90",
	"google":              "https://dv.acme-v02.api.pki.goog/directory",
	"google_staging":      "https://dv.acme-v02.test-api.pki.goog/directory",
}

// ResolverPresets are DNS propagation-check resolvers.
var ResolverPresets = map[string][]string{
	"quad9":      {"9.9.9.9", "149.112.112.112"},
	"cloudflare": {"1.1.1.1", "1.0.0.1"},
	"google":     {"8.8.8.8", "8.8.4.4"},
	"system":     nil,
}

type gen struct {
	in       Input
	w        cf.Writer
	warnings []string
	domains  []model.Domain // sorted longest-first for suffix matching
}

// Generate renders the Caddyfile.
func Generate(in Input) Output {
	g := &gen{in: in}
	g.domains = append([]model.Domain(nil), in.Domains...)
	sort.SliceStable(g.domains, func(i, j int) bool { return len(g.domains[i].Name) > len(g.domains[j].Name) })

	g.w.Comment("Generated by CaddyHub. Do not edit by hand: changes are made in the panel\nand this file is regenerated on every apply. Export is always available.")
	g.global()
	g.snippets()
	g.rawBlocks()
	g.sites()
	return Output{Caddyfile: g.w.String(), Warnings: g.warnings}
}

func (g *gen) warn(format string, a ...any) {
	g.warnings = append(g.warnings, fmt.Sprintf(format, a...))
}

func (g *gen) caURL() string {
	s := g.in.Settings
	if s.ACMECA == "custom" {
		return s.ACMECAURL
	}
	return CAPresets[s.ACMECA]
}

func (g *gen) resolvers(d *model.Domain) []string {
	if d != nil && len(d.Resolvers) > 0 {
		return d.Resolvers
	}
	s := g.in.Settings
	if s.ResolverPreset == "system" {
		return nil
	}
	if s.ResolverPreset != "" && s.ResolverPreset != "custom" {
		if r, ok := ResolverPresets[s.ResolverPreset]; ok {
			return r
		}
	}
	return s.Resolvers
}

// ---------------------------------------------------------------- global

func (g *gen) global() {
	s := g.in.Settings
	e := g.in.Env
	w := &g.w
	w.Open()
	if e.AdminListen != "" {
		if len(e.AdminOrigins) > 0 {
			w.Open("admin", e.AdminListen)
			w.Line(append([]string{"origins"}, e.AdminOrigins...)...)
			w.Close()
		} else {
			w.Line("admin", e.AdminListen)
		}
	}
	if s.ACMEEmail != "" {
		w.Line("email", cf.Q(s.ACMEEmail))
	}
	switch s.ACMECA {
	case "caddy_internal":
		w.Line("local_certs")
	default:
		if u := g.caURL(); u != "" {
			w.Line("acme_ca", cf.Q(u))
		}
		if s.ACMECARoot != "" {
			w.Line("acme_ca_root", cf.Q(s.ACMECARoot))
		}
		if s.ACMEEABKeyID != "" && e.EABMacRef != "" {
			w.Open("acme_eab")
			w.Line("key_id", cf.Q(s.ACMEEABKeyID))
			w.Line("mac_key", cf.Q(e.EABMacRef))
			w.Close()
		}
	}

	g.servers()

	if s.Metrics {
		if g.in.Caps.Has("metrics") {
			w.Open("metrics")
			w.Line("per_host")
			w.Close()
		} else {
			g.warn("metrics disabled: not supported by this Caddy build")
		}
	}

	if s.CrowdSec.Enabled {
		if g.in.Caps.Has("crowdsec") {
			w.Open("crowdsec")
			w.Line("api_url", cf.Q(s.CrowdSec.APIURL))
			if e.CrowdSecKeyRef != "" {
				w.Line("api_key", cf.Q(e.CrowdSecKeyRef))
			}
			if s.CrowdSec.TickerInterval != "" {
				w.Line("ticker_interval", cf.Q(s.CrowdSec.TickerInterval))
			}
			w.Close()
		} else {
			g.warn("CrowdSec is enabled but the crowdsec plugin is not installed; skipped")
		}
	}

	if e.LogDir != "" && !e.ValidationMode {
		w.Open("log")
		w.Open("output", "file", cf.Q(e.LogDir+"/caddy.log"))
		g.roll()
		w.Close()
		w.Line("format", "json")
		w.Close()
	}

	if strings.TrimSpace(s.RawGlobal) != "" {
		w.Comment("raw global options")
		w.Raw(s.RawGlobal)
	}
	w.Close()
}

func (g *gen) roll() {
	s := g.in.Settings
	if s.LogRollSize != "" {
		g.w.Line("roll_size", cf.Q(s.LogRollSize))
	}
	if s.LogRollKeep > 0 {
		g.w.Line("roll_keep", strconv.Itoa(s.LogRollKeep))
	}
}

func (g *gen) servers() {
	tp := g.in.Settings.TrustedProxies
	if !tp.Enabled {
		return
	}
	var ranges []string
	private := false
	seen := map[string]bool{}
	presets := append([]string(nil), tp.Presets...)
	sort.Strings(presets)
	for _, p := range presets {
		if p == "private" {
			private = true
			continue
		}
		r, ok := g.in.Env.TrustedProxyRanges[p]
		if !ok || len(r) == 0 {
			g.warn("trusted proxy preset %q has no ranges loaded yet; skipped", p)
			continue
		}
		for _, c := range r {
			if !seen[c] {
				seen[c] = true
				ranges = append(ranges, c)
			}
		}
	}
	for _, c := range tp.Custom {
		if c = strings.TrimSpace(c); c != "" && !seen[c] {
			seen[c] = true
			ranges = append(ranges, c)
		}
	}
	if len(ranges) == 0 && !private {
		g.warn("trusted proxies enabled but no ranges configured")
		return
	}
	w := &g.w
	w.Open("servers")
	args := []string{"trusted_proxies", "static"}
	if private {
		args = append(args, "private_ranges")
	}
	w.Line(append(args, ranges...)...)
	if tp.Strict {
		w.Line("trusted_proxies_strict")
	}
	if len(tp.ClientIPHeaders) > 0 {
		hs := make([]string, len(tp.ClientIPHeaders))
		for i, h := range tp.ClientIPHeaders {
			hs[i] = cf.Q(h)
		}
		w.Line(append([]string{"client_ip_headers"}, hs...)...)
	}
	w.Close()
}

// ---------------------------------------------------------------- snippets / raw

func (g *gen) snippets() {
	sn := append([]model.Snippet(nil), g.in.Snippets...)
	sort.Slice(sn, func(i, j int) bool { return sn[i].Name < sn[j].Name })
	for _, s := range sn {
		g.w.Blank()
		if s.Description != "" {
			g.w.Comment(s.Description)
		}
		g.w.Open("(" + s.Name + ")")
		g.w.Raw(s.Body)
		g.w.Close()
	}
}

func (g *gen) rawBlocks() {
	rb := append([]model.RawBlock(nil), g.in.RawBlocks...)
	sort.SliceStable(rb, func(i, j int) bool {
		if rb[i].Position != rb[j].Position {
			return rb[i].Position < rb[j].Position
		}
		return rb[i].ID < rb[j].ID
	})
	for _, b := range rb {
		if !b.Enabled || strings.TrimSpace(b.Body) == "" {
			continue
		}
		g.w.Blank()
		g.w.Comment("raw block: " + b.Name)
		g.w.Raw(b.Body)
	}
}

// ---------------------------------------------------------------- sites

// DomainFor returns the managed domain a host belongs to (longest suffix).
func DomainFor(domains []model.Domain, host string) *model.Domain {
	h := strings.ToLower(strings.TrimPrefix(host, "*."))
	var best *model.Domain
	for i := range domains {
		d := &domains[i]
		n := strings.ToLower(d.Name)
		if h == n || strings.HasSuffix(h, "."+n) {
			if best == nil || len(n) > len(best.Name) {
				best = d
			}
		}
	}
	return best
}

func (g *gen) domainFor(host string) *model.Domain { return DomainFor(g.domains, host) }

// dnsUsable reports whether a domain can actually use DNS-01 with the
// installed modules and configured credentials.
func (g *gen) dnsUsable(d *model.Domain) (CredRef, bool) {
	if d == nil || d.Challenge != model.ChallengeDNS || d.CredentialID == nil {
		return CredRef{}, false
	}
	c, ok := g.in.Credentials[*d.CredentialID]
	if !ok {
		return CredRef{}, false
	}
	p, ok := registry.DNSProviderByID(c.Provider)
	if !ok {
		return CredRef{}, false
	}
	if !g.in.Caps.HasModule(p.Module()) {
		return CredRef{}, false
	}
	return c, true
}

func sortedSites(sites []model.Site) []model.Site {
	out := make([]model.Site, 0, len(sites))
	for _, s := range sites {
		if s.Enabled {
			out = append(out, s)
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Position != out[j].Position {
			return out[i].Position < out[j].Position
		}
		return out[i].ID < out[j].ID
	})
	return out
}

func (g *gen) sites() {
	sites := sortedSites(g.in.Sites)

	// Warn once per domain whose DNS challenge can't be used.
	for i := range g.domains {
		d := &g.domains[i]
		if d.Challenge != model.ChallengeDNS {
			continue
		}
		if _, ok := g.dnsUsable(d); !ok {
			g.warn("domain %s: DNS-01 unavailable (missing credential or DNS provider plugin); falling back to HTTP/TLS-ALPN challenges and no wildcard", d.Name)
		}
	}

	// Wildcard grouping: sites whose hosts are all direct subdomains of a
	// wildcard-enabled domain are routed inside the *.domain block so they
	// share its certificate.
	grouped := map[int64][]model.Site{} // domain id -> sites
	var individual []model.Site
	for _, s := range sites {
		if d := g.wildcardDomainFor(s); d != nil {
			grouped[d.ID] = append(grouped[d.ID], s)
			continue
		}
		individual = append(individual, s)
	}

	for _, s := range individual {
		g.w.Blank()
		g.site(s)
	}

	// wildcard blocks in domain-name order
	doms := append([]model.Domain(nil), g.in.Domains...)
	sort.Slice(doms, func(i, j int) bool { return doms[i].Name < doms[j].Name })
	for i := range doms {
		d := &doms[i]
		if !d.Wildcard {
			continue
		}
		if _, ok := g.dnsUsable(d); !ok {
			continue
		}
		g.w.Blank()
		g.wildcardBlock(d, grouped[d.ID])
	}

	if pd := strings.TrimSpace(g.in.Settings.PanelDomain); pd != "" && g.in.Env.PanelUpstream != "" {
		g.w.Blank()
		g.w.Comment("CaddyHub itself")
		g.w.Open(cf.Q(pd))
		g.tlsBlock(pd, model.TLSConfig{})
		g.w.Line("reverse_proxy", cf.Q(g.in.Env.PanelUpstream))
		g.w.Close()
	}
}

func (g *gen) wildcardDomainFor(s model.Site) *model.Domain {
	c := s.Config
	if (c.TLS.Mode != "" && c.TLS.Mode != model.TLSAuto) || c.HTTPRedirect != nil && !*c.HTTPRedirect || c.WWWRedirect != "" || len(s.Hosts) == 0 {
		return nil
	}
	var dom *model.Domain
	for _, h := range s.Hosts {
		d := g.domainFor(h)
		if d == nil || !d.Wildcard {
			return nil
		}
		if _, ok := g.dnsUsable(d); !ok {
			return nil
		}
		sub := strings.TrimSuffix(strings.ToLower(h), "."+strings.ToLower(d.Name))
		if sub == strings.ToLower(h) || sub == "" || strings.Contains(sub, ".") || strings.Contains(sub, "*") {
			return nil
		}
		if dom != nil && dom.ID != d.ID {
			return nil
		}
		dom = d
	}
	return dom
}

func siteMatcherName(s model.Site) string { return "site_" + strconv.FormatInt(s.ID, 10) }

// LogFile returns the access log path of a site.
func LogFile(logDir string, id int64) string {
	return logDir + "/access-site-" + strconv.FormatInt(id, 10) + ".log"
}

func (g *gen) accessLogOn(s model.Site) bool {
	if g.in.Env.LogDir == "" {
		return false
	}
	if s.Config.AccessLog != nil {
		return *s.Config.AccessLog
	}
	return g.in.Settings.DefaultAccessLog
}

func (g *gen) wildcardBlock(d *model.Domain, sites []model.Site) {
	w := &g.w
	w.Comment("wildcard certificate for " + d.Name)
	w.Open(cf.Q("*." + d.Name))
	g.tlsBlock("*."+d.Name, model.TLSConfig{})
	for _, s := range sites {
		if g.accessLogOn(s) {
			w.Open("log", siteMatcherName(s))
			hs := make([]string, len(s.Hosts))
			for i, h := range s.Hosts {
				hs[i] = cf.Q(strings.ToLower(h))
			}
			w.Line(append([]string{"hostnames"}, hs...)...)
			w.Open("output", "file", cf.Q(LogFile(g.in.Env.LogDir, s.ID)))
			g.roll()
			w.Close()
			w.Line("format", "json")
			w.Close()
		}
	}
	for _, s := range sites {
		w.Blank()
		w.Comment(fmt.Sprintf("site %d: %s", s.ID, s.Name))
		hs := make([]string, len(s.Hosts))
		for i, h := range s.Hosts {
			hs[i] = cf.Q(strings.ToLower(h))
		}
		w.Line(append([]string{"@" + siteMatcherName(s), "host"}, hs...)...)
		w.Open("handle", "@"+siteMatcherName(s))
		g.siteBody(s)
		w.Close()
	}
	w.Blank()
	w.Comment("unknown subdomains")
	w.Open("handle")
	w.Line("abort")
	w.Close()
	w.Close()
}

func (g *gen) site(s model.Site) {
	w := &g.w
	c := s.Config
	mode := c.TLS.Mode
	if mode == "" {
		mode = model.TLSAuto
	}
	httpRedirect := c.HTTPRedirect == nil || *c.HTTPRedirect

	type redirect struct{ from, to string }
	hosts := make([]string, 0, len(s.Hosts))
	var redirects []redirect // extra hosts that redirect to the canonical one
	for _, h := range s.Hosts {
		h = strings.ToLower(h)
		plain := !strings.HasPrefix(h, "www.") && !strings.HasPrefix(h, "*.")
		switch {
		case c.WWWRedirect == "to_www" && plain:
			hosts = append(hosts, "www."+h)
			redirects = append(redirects, redirect{from: h, to: "www." + h})
			continue
		case c.WWWRedirect == "to_apex" && plain:
			redirects = append(redirects, redirect{from: "www." + h, to: h})
		}
		hosts = append(hosts, h)
	}
	addrs := g.addresses(hosts, mode, httpRedirect)

	w.Comment(fmt.Sprintf("site %d: %s", s.ID, s.Name))
	w.Open(strings.Join(addrs, ", "))
	if mode != model.TLSOff {
		g.tlsBlock(firstOr(hosts, ""), c.TLS)
	}
	if g.accessLogOn(s) {
		w.Open("log")
		w.Open("output", "file", cf.Q(LogFile(g.in.Env.LogDir, s.ID)))
		g.roll()
		w.Close()
		w.Line("format", "json")
		w.Close()
	}
	g.siteBody(s)
	w.Close()

	scheme := "https://"
	if mode == model.TLSOff {
		scheme = "http://"
	}
	for _, r := range redirects {
		w.Blank()
		w.Comment(fmt.Sprintf("site %d: www redirect", s.ID))
		w.Open(strings.Join(g.addresses([]string{r.from}, mode, httpRedirect), ", "))
		if mode != model.TLSOff {
			g.tlsBlock(r.from, c.TLS)
		}
		w.Line("redir", cf.Q(scheme+r.to+"{uri}"), "permanent")
		w.Close()
	}
}

func firstOr(s []string, d string) string {
	if len(s) > 0 {
		return s[0]
	}
	return d
}

func (g *gen) addresses(hosts []string, mode string, httpRedirect bool) []string {
	var out []string
	for _, h := range hosts {
		switch {
		case mode == model.TLSOff:
			out = append(out, "http://"+h)
		case !httpRedirect:
			out = append(out, "http://"+h, "https://"+h)
		default:
			out = append(out, h)
		}
	}
	return out
}

// tlsBlock emits the tls directive for a site.
func (g *gen) tlsBlock(host string, t model.TLSConfig) {
	w := &g.w
	switch t.Mode {
	case model.TLSInternal:
		w.Line("tls", "internal")
		return
	case model.TLSCustom:
		if t.CertFile == "" || t.KeyFile == "" {
			g.warn("site %s: custom TLS selected without cert/key files; using automatic TLS", host)
			break
		}
		w.Line("tls", cf.Q(t.CertFile), cf.Q(t.KeyFile))
		return
	case model.TLSOff:
		return
	}
	if g.in.Settings.ACMECA == "caddy_internal" {
		return // local_certs global handles it
	}
	d := g.domainFor(host)
	if d == nil {
		return // global defaults
	}
	cred, dnsOK := g.dnsUsable(d)
	challenge := d.Challenge
	if challenge == model.ChallengeDNS && !dnsOK {
		challenge = "" // fallback: let Caddy pick HTTP/TLS-ALPN
	}
	if challenge == "" && g.caURL() == "" {
		return
	}
	w.Open("tls")
	w.Open("issuer", "acme")
	if u := g.caURL(); u != "" {
		w.Line("dir", cf.Q(u))
	}
	if e := g.in.Settings.ACMEEmail; e != "" {
		w.Line("email", cf.Q(e))
	}
	if g.in.Settings.ACMEEABKeyID != "" && g.in.Env.EABMacRef != "" {
		w.Line("eab", cf.Q(g.in.Settings.ACMEEABKeyID), cf.Q(g.in.Env.EABMacRef))
	}
	if g.in.Settings.ACMECARoot != "" {
		w.Line("trusted_roots", cf.Q(g.in.Settings.ACMECARoot))
	}
	switch challenge {
	case model.ChallengeHTTP:
		w.Line("disable_tlsalpn_challenge")
	case model.ChallengeTLSALPN:
		w.Line("disable_http_challenge")
	case model.ChallengeDNS:
		w.Line("disable_http_challenge")
		w.Line("disable_tlsalpn_challenge")
		g.dnsDirective(cred)
		if r := g.resolvers(d); len(r) > 0 {
			w.Line(append([]string{"resolvers"}, r...)...)
		}
		pd := firstNonEmpty(d.PropagationDelay, g.in.Settings.PropagationDelay)
		pt := firstNonEmpty(d.PropagationTimeout, g.in.Settings.PropagationTimeout)
		if pd != "" {
			w.Line("propagation_delay", cf.Q(pd))
		}
		if pt != "" {
			w.Line("propagation_timeout", cf.Q(pt))
		}
	}
	w.Close()
	w.Close()
}

func firstNonEmpty(a ...string) string {
	for _, s := range a {
		if s != "" {
			return s
		}
	}
	return ""
}

func (g *gen) dnsDirective(c CredRef) {
	p, _ := registry.DNSProviderByID(c.Provider)
	w := &g.w
	w.Open("dns", c.Provider)
	for _, f := range p.Fields { // registry order keeps output stable
		v, ok := c.Fields[f.Key]
		if !ok || v == "" {
			continue
		}
		w.Line(f.Key, cf.Q(v))
	}
	w.Close()
}

// siteBody emits everything inside a site (or wildcard handle) block except
// addresses, tls and log.
func (g *gen) siteBody(s model.Site) {
	w := &g.w
	c := s.Config
	caps := g.in.Caps

	snips := append([]string(nil), c.Snippets...)
	for _, name := range snips {
		w.Line("import", cf.Q(name))
	}

	if len(c.Compression) > 0 {
		var enc []string
		for _, e := range c.Compression {
			if caps.Has("encode_" + e) {
				enc = append(enc, e)
			} else {
				g.warn("site %d: compression %q not available; skipped", s.ID, e)
			}
		}
		if len(enc) > 0 {
			w.Line(append([]string{"encode"}, enc...)...)
		}
	}

	if len(c.HeadersSet) > 0 || len(c.HeadersRemove) > 0 {
		w.Open("header")
		for _, k := range sortedKeys(c.HeadersSet) {
			w.Line(cf.Q(k), cf.Q(c.HeadersSet[k]))
		}
		rm := append([]string(nil), c.HeadersRemove...)
		sort.Strings(rm)
		for _, k := range rm {
			w.Line(cf.Q("-" + k))
		}
		w.Close()
	}

	if c.MaxBodySize != "" {
		w.Open("request_body")
		w.Line("max_size", cf.Q(c.MaxBodySize))
		w.Close()
	}

	// Everything that must run in a strict order goes in one route block:
	// security checks first, then path routes, then the main handler.
	// (Caddy's default directive order runs handle/route before respond,
	// so without this a deny rule could be bypassed.)
	a := c.Access
	needRoute := a.CrowdSec || len(a.DenyCIDRs) > 0 || len(a.AllowCIDRs) > 0 ||
		(a.RateLimit != nil && a.RateLimit.Events > 0) || len(a.BasicAuth) > 0 ||
		(a.ForwardAuth != nil && a.ForwardAuth.Upstream != "") || c.Maintenance || len(c.Routes) > 0
	if needRoute {
		w.Open("route")
	}
	if a.CrowdSec {
		if caps.Has("crowdsec") && g.in.Settings.CrowdSec.Enabled {
			w.Line("crowdsec")
		} else {
			g.warn("site %d: CrowdSec requested but not enabled/installed; skipped", s.ID)
		}
	}
	if len(a.DenyCIDRs) > 0 {
		w.Line(append([]string{"@cp_denied", "client_ip"}, a.DenyCIDRs...)...)
		w.Line("respond", "@cp_denied", cf.Q("Forbidden"), "403")
	}
	if len(a.AllowCIDRs) > 0 {
		w.Line(append([]string{"@cp_not_allowed", "not", "client_ip"}, a.AllowCIDRs...)...)
		w.Line("respond", "@cp_not_allowed", cf.Q("Forbidden"), "403")
	}
	if rl := a.RateLimit; rl != nil && rl.Events > 0 {
		if caps.Has("rate_limit") {
			w.Open("rate_limit")
			w.Open("zone", siteMatcherName(s))
			key := rl.Key
			if key == "" {
				key = "{client_ip}"
			}
			w.Line("key", cf.Q(key))
			w.Line("events", strconv.Itoa(rl.Events))
			win := rl.Window
			if win == "" {
				win = "1m"
			}
			w.Line("window", cf.Q(win))
			w.Close()
			w.Close()
		} else {
			g.warn("site %d: rate limiting requested but caddy-ratelimit is not installed; skipped", s.ID)
		}
	}
	if len(a.BasicAuth) > 0 {
		w.Open("basic_auth")
		for _, u := range a.BasicAuth {
			w.Line(cf.Q(u.Username), cf.Q(u.Hash))
		}
		w.Close()
	}
	if fa := a.ForwardAuth; fa != nil && fa.Upstream != "" {
		w.Open("forward_auth", cf.Q(fa.Upstream))
		uri := fa.URI
		if uri == "" {
			uri = "/"
		}
		w.Line("uri", cf.Q(uri))
		if len(fa.CopyHeaders) > 0 {
			hs := make([]string, len(fa.CopyHeaders))
			for i, h := range fa.CopyHeaders {
				hs[i] = cf.Q(h)
			}
			w.Line(append([]string{"copy_headers"}, hs...)...)
		}
		w.Close()
	}

	if c.Maintenance {
		body := c.MaintenanceBody
		if body == "" {
			body = "Down for maintenance. Please check back soon."
		}
		w.Line("header", "Retry-After", "300")
		w.Line("respond", cf.Q(body), "503")
	} else {
		for i, r := range c.Routes {
			if r.Path == "" {
				continue
			}
			dir := "handle"
			if r.StripPrefix {
				dir = "handle_path"
			}
			w.Open(dir, cf.Q(r.Path))
			g.handler(s.ID, i, r.Kind, r.Proxy, r.Static, r.Redirect, r.Respond)
			w.Close()
		}
		if len(c.Routes) > 0 {
			w.Open("handle")
			g.handler(s.ID, -1, s.Kind, c.Proxy, c.Static, c.Redirect, c.Respond)
			w.Close()
		} else {
			g.handler(s.ID, -1, s.Kind, c.Proxy, c.Static, c.Redirect, c.Respond)
		}
	}
	if needRoute {
		w.Close()
	}

	if strings.TrimSpace(c.Raw) != "" {
		w.Comment("raw site snippet")
		w.Raw(c.Raw)
	}
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func (g *gen) handler(siteID int64, route int, kind string, p *model.ProxyConfig, st *model.StaticConfig, rd *model.RedirectConfig, rs *model.RespondConfig) {
	w := &g.w
	where := fmt.Sprintf("site %d", siteID)
	if route >= 0 {
		where = fmt.Sprintf("site %d route %d", siteID, route+1)
	}
	switch kind {
	case model.KindProxy:
		if p == nil || len(p.Upstreams) == 0 {
			g.warn("%s: reverse proxy has no upstreams", where)
			w.Line("respond", cf.Q("No upstream configured"), "502")
			return
		}
		g.proxy(p)
	case model.KindStatic:
		if st == nil || st.Root == "" {
			g.warn("%s: static site has no root", where)
			w.Line("respond", cf.Q("No root configured"), "500")
			return
		}
		w.Line("root", "*", cf.Q(st.Root))
		if st.SPA {
			w.Line("try_files", "{path}", "/index.html")
		}
		if st.Browse {
			w.Line("file_server", "browse")
		} else {
			w.Line("file_server")
		}
	case model.KindRedirect:
		if rd == nil || rd.To == "" {
			g.warn("%s: redirect has no target", where)
			return
		}
		to := rd.To
		if rd.KeepPath {
			to = strings.TrimRight(to, "/") + "{uri}"
		}
		code := rd.Code
		if code == 0 {
			code = 302
		}
		w.Line("redir", cf.Q(to), strconv.Itoa(code))
	case model.KindRespond:
		body, status, ctype := "", 200, ""
		if rs != nil {
			body, ctype = rs.Body, rs.ContentType
			if rs.Status != 0 {
				status = rs.Status
			}
		}
		if ctype != "" {
			w.Line("header", "Content-Type", cf.Q(ctype))
		}
		if body != "" {
			w.Line("respond", cf.Q(body), strconv.Itoa(status))
		} else {
			w.Line("respond", strconv.Itoa(status))
		}
	case model.KindNone:
		// handled entirely by the raw snippet
	default:
		g.warn("%s: unknown kind %q", where, kind)
	}
}

func (g *gen) proxy(p *model.ProxyConfig) {
	w := &g.w
	ups := make([]string, len(p.Upstreams))
	for i, u := range p.Upstreams {
		ups[i] = cf.Q(strings.TrimSpace(u))
	}
	var lines [][]string
	add := func(t ...string) { lines = append(lines, t) }
	if p.LBPolicy != "" {
		add("lb_policy", p.LBPolicy)
	}
	if p.LBRetries > 0 {
		add("lb_retries", strconv.Itoa(p.LBRetries))
	}
	if p.LBTryDuration != "" {
		add("lb_try_duration", cf.Q(p.LBTryDuration))
	}
	if p.HealthURI != "" {
		add("health_uri", cf.Q(p.HealthURI))
		if p.HealthInterval != "" {
			add("health_interval", cf.Q(p.HealthInterval))
		}
		if p.HealthTimeout != "" {
			add("health_timeout", cf.Q(p.HealthTimeout))
		}
		if p.HealthStatus != "" {
			add("health_status", cf.Q(p.HealthStatus))
		}
	}
	if p.FailDuration != "" {
		add("fail_duration", cf.Q(p.FailDuration))
		if p.MaxFails > 0 {
			add("max_fails", strconv.Itoa(p.MaxFails))
		}
		if p.UnhealthyStatus != "" {
			add("unhealthy_status", cf.Q(p.UnhealthyStatus))
		}
	}
	if p.FlushInterval != "" {
		add("flush_interval", cf.Q(p.FlushInterval))
	}
	if p.PassHostHeader != nil && !*p.PassHostHeader {
		add("header_up", "Host", "{upstream_hostport}")
	}
	for _, k := range sortedKeys(p.HeaderUp) {
		add("header_up", cf.Q(k), cf.Q(p.HeaderUp[k]))
	}
	for _, k := range sortedKeys(p.HeaderDown) {
		add("header_down", cf.Q(k), cf.Q(p.HeaderDown[k]))
	}

	var tr [][]string
	tadd := func(t ...string) { tr = append(tr, t) }
	if p.DialTimeout != "" {
		tadd("dial_timeout", cf.Q(p.DialTimeout))
	}
	if p.ResponseHeaderTimeout != "" {
		tadd("response_header_timeout", cf.Q(p.ResponseHeaderTimeout))
	}
	if p.ReadTimeout != "" {
		tadd("read_timeout", cf.Q(p.ReadTimeout))
	}
	if p.WriteTimeout != "" {
		tadd("write_timeout", cf.Q(p.WriteTimeout))
	}
	if p.TLSSkipVerify || p.TLSServerName != "" {
		if !anyHasScheme(p.Upstreams, "https://") {
			tadd("tls")
		}
		if p.TLSSkipVerify {
			tadd("tls_insecure_skip_verify")
		}
		if p.TLSServerName != "" {
			tadd("tls_server_name", cf.Q(p.TLSServerName))
		}
	}
	switch {
	case p.H2C:
		tadd("versions", "h2c", "2")
	case p.HTTP2:
		tadd("versions", "2")
	}

	if len(lines) == 0 && len(tr) == 0 {
		w.Line(append([]string{"reverse_proxy"}, ups...)...)
		return
	}
	w.Open(append([]string{"reverse_proxy"}, ups...)...)
	for _, l := range lines {
		w.Line(l...)
	}
	if len(tr) > 0 {
		w.Open("transport", "http")
		for _, l := range tr {
			w.Line(l...)
		}
		w.Close()
	}
	w.Close()
}

func anyHasScheme(ups []string, scheme string) bool {
	for _, u := range ups {
		if strings.HasPrefix(strings.ToLower(strings.TrimSpace(u)), scheme) {
			return true
		}
	}
	return false
}
